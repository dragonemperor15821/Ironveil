
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.Rendering;

[RequireComponent(typeof(MeshFilter), typeof(MeshRenderer))]
public class RailGenerator : MonoBehaviour
{
    [Header("Terrain")]
    [SerializeField] private Collider terrainCollider;

    [Header("Materials")]
    [SerializeField] private Material railMaterial;
    [SerializeField] private Material sleeperMaterial;

    [Header("Rail Appearance")]
    // Sized to fit inside the Rail Hangar footprints (0.2 x 0.13 m at the
    // prefabs' authored 0.2 scale). Adjust independently as needed.
    [Tooltip("Distance between the two rail centrelines.")]
    [SerializeField, Min(0.01f)] private float railGauge = 0.09f;

    [Tooltip("Rail head width, measured across the track.")]
    [SerializeField, Min(0.005f)] private float railWidth = 0.015f;

    [Tooltip("Rail thickness, measured vertically.")]
    [SerializeField, Min(0.005f)] private float railHeight = 0.02f;

    [Tooltip("Sleeper length, measured across the track.")]
    [SerializeField, Min(0.02f)] private float sleeperLength = 0.11f;

    [Tooltip("Sleeper length, measured along the track.")]
    [SerializeField, Min(0.005f)] private float sleeperWidth = 0.03f;

    [Tooltip("Sleeper thickness, measured vertically.")]
    [SerializeField, Min(0.005f)] private float sleeperHeight = 0.012f;

    [Tooltip("Height of the rail base plane above the terrain.")]
    [SerializeField, Min(0f)] private float surfaceOffset = 0.02f;

    [Tooltip("World distance between consecutive sleepers along the track.")]
    [SerializeField, Min(0.01f)] private float sleeperSpacing = 0.3f;

    [Header("Route")]
    [SerializeField] private int seed = 24680;
    [SerializeField] private Vector2 mapCenter = Vector2.zero;
    [SerializeField] private Vector2 mapSize = new Vector2(400f, 400f);
    [SerializeField, Min(1f)] private float edgePadding = 15f;
    [SerializeField, Min(0f)] private float bendAmount = 75f;
    [SerializeField, Range(3, 12)] private int controlPointCount = 9;
    [SerializeField, Range(0f, 1f)] private float windingAmount = 0.75f;
    [SerializeField, Min(20)] private int pointCount = 240;

    [Header("River Avoidance")]
    [SerializeField] private RiverGenerator riverToAvoid;
    [SerializeField] private bool avoidRiver = true;
    [SerializeField, Min(0f)] private float minimumRiverClearance = 35f;
    [SerializeField, Range(1, 150)] private int routeCandidates = 100;

    [Header("Generation")]
    [SerializeField] private bool generateOnStart = false;

    private Mesh railMesh;
    private Mesh sleeperMesh;
    private Transform sleeperRoot;

    // Public route access for BaseSpawner.
    // Points are in world coordinates, as generated by BuildRoute().
    private readonly List<Vector3> generatedRoute = new List<Vector3>();
    public IReadOnlyList<Vector3> GeneratedRoute => generatedRoute;

    // Half-width of the visible rail corridor (rails and sleepers).
    // Used by BaseSpawner to validate that bases sit outside the corridor.
    public float RailCorridorHalfWidth =>
        Mathf.Max(
            railGauge * 0.5f + railWidth * 0.5f,
            sleeperLength * 0.5f);

    // Distance between the two rail centrelines. Exposed so BaseSpawner can
    // validate that the hangar is wide enough to cover both rails.
    public float RailGauge => railGauge;

    private void Start()
    {
        if (generateOnStart)
            GenerateRail();
    }

    [ContextMenu("Generate Rail")]
    public void GenerateRail()
    {
        if (terrainCollider == null ||
            railMaterial == null ||
            sleeperMaterial == null)
        {
            Debug.LogError(
                "RailGenerator: Assign Terrain Collider, Rail Material and Sleeper Material.",
                this);
            return;
        }

        if (mapSize.x <= edgePadding * 2f ||
            mapSize.y <= edgePadding * 2f ||
            pointCount < 2 ||
            controlPointCount < 3)
        {
            Debug.LogError(
                "RailGenerator: Check map size, point count and controls.",
                this);
            return;
        }

        Random.State previousRandomState = Random.state;
        Random.InitState(seed);

        List<Vector3> bestRoute = null;
        float bestScore = float.NegativeInfinity;

        int candidateCount = avoidRiver && riverToAvoid != null
            ? routeCandidates
            : 1;

        for (int i = 0; i < candidateCount; i++)
        {
            List<Vector3> candidate = BuildRoute();
            float score = ScoreRoute(candidate);

            if (score > bestScore)
            {
                bestScore = score;
                bestRoute = candidate;
            }
        }

        if (bestRoute == null || bestRoute.Count < 2)
        {
            Random.state = previousRandomState;
            Debug.LogError(
                "RailGenerator: Could not create a valid route.",
                this);
            return;
        }

        // Expose the exact route used to generate the visible tracks.
        generatedRoute.Clear();
        generatedRoute.AddRange(bestRoute);

        BuildRailMesh(bestRoute);
        BuildSleeperMesh(bestRoute);

        Random.state = previousRandomState;

        Debug.Log(
            $"RailGenerator: Generated railway with {bestRoute.Count} route points using seed {seed}.",
            this);
    }

    private List<Vector3> BuildRoute()
    {
        float minX = mapCenter.x - mapSize.x * 0.5f + edgePadding;
        float maxX = mapCenter.x + mapSize.x * 0.5f - edgePadding;
        float minZ = mapCenter.y - mapSize.y * 0.5f + edgePadding;
        float maxZ = mapCenter.y + mapSize.y * 0.5f - edgePadding;

        Vector3 start;
        Vector3 end;

        if (Random.value < 0.5f)
        {
            start = new Vector3(minX, 0f, Random.Range(minZ, maxZ));
            end = new Vector3(maxX, 0f, Random.Range(minZ, maxZ));
        }
        else
        {
            start = new Vector3(Random.Range(minX, maxX), 0f, minZ);
            end = new Vector3(Random.Range(minX, maxX), 0f, maxZ);
        }

        Vector3 forward = (end - start).normalized;
        Vector3 sideways = new Vector3(-forward.z, 0f, forward.x);

        List<Vector3> controls = new List<Vector3> { start };

        for (int i = 1; i < controlPointCount - 1; i++)
        {
            float t = i / (float)(controlPointCount - 1);
            float envelope = Mathf.Sin(t * Mathf.PI);

            Vector3 p = Vector3.Lerp(start, end, t);

            p += sideways *
                 Random.Range(-bendAmount, bendAmount) *
                 windingAmount * envelope;

            p += forward *
                 Random.Range(-bendAmount * 0.45f, bendAmount * 0.45f) *
                 windingAmount * envelope;

            p.x = Mathf.Clamp(p.x, minX, maxX);
            p.z = Mathf.Clamp(p.z, minZ, maxZ);

            controls.Add(p);
        }

        controls.Add(end);

        List<Vector3> route = new List<Vector3>(pointCount);

        for (int i = 0; i < pointCount; i++)
        {
            float t = i / (float)(pointCount - 1);
            Vector3 p = EvaluateSpline(controls, t);
            route.Add(ProjectOntoTerrain(p));
        }

        return route;
    }

    private float ScoreRoute(List<Vector3> route)
    {
        if (!avoidRiver ||
            riverToAvoid == null ||
            riverToAvoid.GeneratedRoute == null ||
            riverToAvoid.GeneratedRoute.Count == 0)
        {
            return Random.value;
        }

        IReadOnlyList<Vector3> river = riverToAvoid.GeneratedRoute;

        float totalDistance = 0f;
        float penalty = 0f;
        float minimumDistance = float.MaxValue;

        int sampleStep = Mathf.Max(1, route.Count / 40);

        for (int i = 0; i < route.Count; i += sampleStep)
        {
            Vector3 railPoint = route[i];
            float nearestDistance = float.MaxValue;

            for (int j = 0; j < river.Count; j += 2)
            {
                float distance = Vector2.Distance(
                    new Vector2(railPoint.x, railPoint.z),
                    new Vector2(river[j].x, river[j].z));

                if (distance < nearestDistance)
                    nearestDistance = distance;
            }

            totalDistance += nearestDistance;
            minimumDistance = Mathf.Min(minimumDistance, nearestDistance);

            if (nearestDistance < minimumRiverClearance)
            {
                float shortfall = minimumRiverClearance - nearestDistance;
                penalty += shortfall * shortfall;
            }
        }

        float samples = Mathf.CeilToInt(route.Count / (float)sampleStep);
        float averageDistance = totalDistance / Mathf.Max(1f, samples);

        return averageDistance - penalty * 0.15f + minimumDistance * 0.25f;
    }

    private void BuildRailMesh(List<Vector3> route)
    {
        List<Vector3> vertices = new List<Vector3>();
        List<int> triangles = new List<int>();
        List<Vector2> uvs = new List<Vector2>();

        for (int sideIndex = 0; sideIndex < 2; sideIndex++)
        {
            float sideOffset = sideIndex == 0
                ? -railGauge * 0.5f
                : railGauge * 0.5f;

            int startVertex = vertices.Count;

            // Four vertices per route point: a box cross-section of the
            // rail (bottom-left, bottom-right, top-left, top-right).
            for (int i = 0; i < route.Count; i++)
            {
                Vector3 tangent = GetTangent(route, i);
                Vector3 side = Vector3.Cross(Vector3.up, tangent).normalized;

                Vector3 center = route[i] + side * sideOffset;
                center.y += surfaceOffset;

                Vector3 left = center - side * railWidth * 0.5f;
                Vector3 right = center + side * railWidth * 0.5f;

                vertices.Add(transform.InverseTransformPoint(left));
                vertices.Add(transform.InverseTransformPoint(right));
                vertices.Add(transform.InverseTransformPoint(
                    left + Vector3.up * railHeight));
                vertices.Add(transform.InverseTransformPoint(
                    right + Vector3.up * railHeight));

                float uvLength = i / (float)(route.Count - 1) * 12f;
                float uvAcross = sideIndex == 0 ? 0.0f : 0.5f;

                uvs.Add(new Vector2(uvAcross, uvLength));
                uvs.Add(new Vector2(uvAcross + 0.5f, uvLength));
                uvs.Add(new Vector2(uvAcross, uvLength));
                uvs.Add(new Vector2(uvAcross + 0.5f, uvLength));
            }

            // Three quads per segment: top face and both side faces.
            for (int i = 0; i < route.Count - 1; i++)
            {
                int v = startVertex + i * 4;
                int w = v + 4;

                // Top face (normal up).
                triangles.Add(v + 2);
                triangles.Add(w + 2);
                triangles.Add(v + 3);

                triangles.Add(v + 3);
                triangles.Add(w + 2);
                triangles.Add(w + 3);

                // Outer side face (normal away from the track centre).
                triangles.Add(v);
                triangles.Add(w);
                triangles.Add(v + 2);

                triangles.Add(w);
                triangles.Add(w + 2);
                triangles.Add(v + 2);

                // Inner side face (normal toward the track centre).
                triangles.Add(v + 1);
                triangles.Add(v + 3);
                triangles.Add(w + 1);

                triangles.Add(w + 1);
                triangles.Add(v + 3);
                triangles.Add(w + 3);
            }
        }

        Mesh mesh = CreateMesh(
            "GeneratedRailMesh", vertices, triangles, uvs);

        ReplaceMesh(ref railMesh, mesh, GetComponent<MeshFilter>());
        GetComponent<MeshRenderer>().sharedMaterial = railMaterial;
    }

    private void BuildSleeperMesh(List<Vector3> route)
    {
        List<Vector3> vertices = new List<Vector3>();
        List<int> triangles = new List<int>();
        List<Vector2> uvs = new List<Vector2>();

        // Place sleepers at fixed world-space intervals along the route so
        // sleeper density does not depend on the route point spacing.
        float spacing = Mathf.Max(0.01f, sleeperSpacing);
        float travelled = 0f;
        float nextSleeper = 0f;
        Vector3 previous = route[0];

        for (int i = 1; i < route.Count; i++)
        {
            Vector3 current = route[i];
            Vector3 segment = current - previous;
            float segmentLength = segment.magnitude;

            while (nextSleeper <= travelled + segmentLength)
            {
                float t = segmentLength > 0.0001f
                    ? (nextSleeper - travelled) / segmentLength
                    : 0f;

                Vector3 center = Vector3.Lerp(previous, current, t);

                Vector3 direction = segment;
                direction.y = 0f;
                direction = direction.sqrMagnitude > 0.0001f
                    ? direction.normalized
                    : Vector3.forward;

                AddSleeper(center, direction, vertices, triangles, uvs);

                nextSleeper += spacing;
            }

            travelled += segmentLength;
            previous = current;
        }

        Mesh mesh = CreateMesh(
            "GeneratedSleepersMesh", vertices, triangles, uvs);

        if (sleeperRoot == null)
        {
            Transform existing = transform.Find("Generated Sleepers");

            if (existing != null)
            {
                sleeperRoot = existing;
            }
            else
            {
                GameObject child = new GameObject("Generated Sleepers");
                sleeperRoot = child.transform;
                sleeperRoot.SetParent(transform, false);
            }
        }

        sleeperRoot.localPosition = Vector3.zero;
        sleeperRoot.localRotation = Quaternion.identity;
        sleeperRoot.localScale = Vector3.one;

        MeshFilter filter = sleeperRoot.GetComponent<MeshFilter>();
        if (filter == null)
            filter = sleeperRoot.gameObject.AddComponent<MeshFilter>();

        MeshRenderer renderer = sleeperRoot.GetComponent<MeshRenderer>();
        if (renderer == null)
            renderer = sleeperRoot.gameObject.AddComponent<MeshRenderer>();

        ReplaceMesh(ref sleeperMesh, mesh, filter);
        renderer.sharedMaterial = sleeperMaterial;
    }

    private void AddSleeper(
        Vector3 center,
        Vector3 tangent,
        List<Vector3> vertices,
        List<int> triangles,
        List<Vector2> uvs)
    {
        Vector3 acrossTrack = Vector3.Cross(Vector3.up, tangent).normalized;

        center.y += surfaceOffset * 0.7f;

        Vector3 a = center - acrossTrack * sleeperLength * 0.5f;
        Vector3 b = center + acrossTrack * sleeperLength * 0.5f;

        a.y += sleeperHeight;
        b.y += sleeperHeight;

        Vector3 aBack = a - tangent * sleeperWidth * 0.5f;
        Vector3 aFront = a + tangent * sleeperWidth * 0.5f;
        Vector3 bBack = b - tangent * sleeperWidth * 0.5f;
        Vector3 bFront = b + tangent * sleeperWidth * 0.5f;

        int v = vertices.Count;

        vertices.Add(transform.InverseTransformPoint(aBack));
        vertices.Add(transform.InverseTransformPoint(aFront));
        vertices.Add(transform.InverseTransformPoint(bBack));
        vertices.Add(transform.InverseTransformPoint(bFront));

        uvs.Add(new Vector2(0f, 0f));
        uvs.Add(new Vector2(0f, 1f));
        uvs.Add(new Vector2(1f, 0f));
        uvs.Add(new Vector2(1f, 1f));

        // Top face, wound to be visible from above.
        triangles.Add(v);
        triangles.Add(v + 1);
        triangles.Add(v + 2);

        triangles.Add(v + 1);
        triangles.Add(v + 3);
        triangles.Add(v + 2);
    }

    private Vector3 ProjectOntoTerrain(Vector3 point)
    {
        Bounds bounds = terrainCollider.bounds;

        Ray ray = new Ray(
            new Vector3(point.x, bounds.max.y + 100f, point.z),
            Vector3.down);

        if (terrainCollider.Raycast(
            ray, out RaycastHit hit, bounds.size.y + 200f))
        {
            point.y = hit.point.y;
        }
        else
        {
            point.y = bounds.min.y;
        }

        return point;
    }

    private static Vector3 EvaluateSpline(List<Vector3> points, float t)
    {
        float scaled = Mathf.Clamp01(t) * (points.Count - 1);
        int i = Mathf.Min(Mathf.FloorToInt(scaled), points.Count - 2);
        float u = scaled - i;

        return CatmullRom(
            points[Mathf.Max(0, i - 1)],
            points[i],
            points[i + 1],
            points[Mathf.Min(points.Count - 1, i + 2)],
            u);
    }

    private static Vector3 CatmullRom(
        Vector3 p0, Vector3 p1, Vector3 p2, Vector3 p3, float t)
    {
        float t2 = t * t;
        float t3 = t2 * t;

        return 0.5f * (
            2f * p1 +
            (-p0 + p2) * t +
            (2f * p0 - 5f * p1 + 4f * p2 - p3) * t2 +
            (-p0 + 3f * p1 - 3f * p2 + p3) * t3);
    }

    private static Vector3 GetTangent(List<Vector3> points, int index)
    {
        Vector3 tangent;

        if (index == 0)
            tangent = points[1] - points[0];
        else if (index == points.Count - 1)
            tangent = points[index] - points[index - 1];
        else
            tangent = points[index + 1] - points[index - 1];

        tangent.y = 0f;

        return tangent.sqrMagnitude > 0.0001f
            ? tangent.normalized
            : Vector3.forward;
    }

    private static Mesh CreateMesh(
        string meshName,
        List<Vector3> vertices,
        List<int> triangles,
        List<Vector2> uvs)
    {
        Mesh mesh = new Mesh
        {
            name = meshName,
            indexFormat = vertices.Count > 65535
                ? IndexFormat.UInt32
                : IndexFormat.UInt16
        };

        mesh.SetVertices(vertices);
        mesh.SetTriangles(triangles, 0);
        mesh.SetUVs(0, uvs);
        mesh.RecalculateNormals();
        mesh.RecalculateBounds();

        return mesh;
    }

    private void ReplaceMesh(
        ref Mesh oldMesh, Mesh newMesh, MeshFilter filter)
    {
        if (oldMesh != null)
        {
            if (Application.isPlaying)
                Destroy(oldMesh);
            else
                DestroyImmediate(oldMesh);
        }

        oldMesh = newMesh;
        filter.sharedMesh = newMesh;
    }

    private void OnDestroy()
    {
        if (railMesh != null)
        {
            if (Application.isPlaying)
                Destroy(railMesh);
            else
                DestroyImmediate(railMesh);
        }

        if (sleeperMesh != null)
        {
            if (Application.isPlaying)
                Destroy(sleeperMesh);
            else
                DestroyImmediate(sleeperMesh);
        }
    }
}